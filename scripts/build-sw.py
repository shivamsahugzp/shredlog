#!/usr/bin/env python3
"""Regenerate sw.js with the full precache list and a content hash as the cache version."""
import hashlib, os, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
files = []
for p in sorted(root.rglob('*')):
    if p.is_dir(): continue
    rel = p.relative_to(root).as_posix()
    if rel.startswith(('.git/', 'scripts/', 'test/', 'docs/')) or rel in ('sw.js', 'README.md', '.gitignore', 'js/version.js') or rel.endswith('.svg'):
        continue
    files.append(rel)
h = hashlib.sha1()
for f in files:
    h.update(f.encode()); h.update((root / f).read_bytes())
h.update(b'sw-template-2')  # bump when the worker script itself changes, so the cache name changes too
version = h.hexdigest()[:10]
import datetime
(root / 'js' / 'version.js').write_text(f"// Generated by scripts/build-sw.py. Shown in Settings so a phone can tell which build it runs.\nexport const VERSION = '{version}';\nexport const BUILT = '{datetime.date.today().isoformat()}';\n")
files.append('js/version.js')
urls = ['./'] + ['./' + f for f in files]
sw = f"""// ShredLog service worker — generated by scripts/build-sw.py
const VERSION = 'shredlog-{version}';
const PRECACHE = {urls!r};

// A new build takes over as soon as it is downloaded (skipWaiting + claim); the page reloads itself on controllerchange.
// Without this a phone that missed the "Update ready" toast keeps running the old build for days.
self.addEventListener('install', (e) => {{
  e.waitUntil(caches.open(VERSION).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
}});
self.addEventListener('activate', (e) => {{
  e.waitUntil((async () => {{
    const keys = await caches.keys();
    await Promise.all(keys.filter((k) => k !== VERSION).map((k) => caches.delete(k)));
    await self.clients.claim();
  }})());
}});
self.addEventListener('message', (e) => {{ if (e.data === 'SKIP_WAITING') self.skipWaiting(); }});
self.addEventListener('fetch', (e) => {{
  const req = e.request;
  if (req.method !== 'GET' || new URL(req.url).origin !== location.origin) return;
  e.respondWith((async () => {{
    const cache = await caches.open(VERSION);
    const hit = await cache.match(req, {{ ignoreSearch: true }});
    if (hit) return hit;
    try {{
      const res = await fetch(req);
      if (res.ok) cache.put(req, res.clone());
      return res;
    }} catch (err) {{
      if (req.mode === 'navigate') return cache.match('./index.html');
      throw err;
    }}
  }})());
}});
"""
(root / 'sw.js').write_text(sw.replace("'./'] + ", "'./', "))
print(f'sw.js written: version {version}, {len(urls)} urls')
